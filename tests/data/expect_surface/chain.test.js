  await t('assert.strictEqual', () => assert.strictEqual(1, '1'))
  await t('assert.deepEqual', () => assert.deepEqual({ a: 1 }, { a: 2 }))
  await t('assert.isTrue', () => assert.isTrue(1))
  await t('assert.isOk', () => assert.isOk(0, 'why'))
  await t('assert.include', () => assert.include([1], 2))
  await t('assert.throws', () => assert.throws(() => {}))
  await t('assert.lengthOf', () => assert.lengthOf([1], 2))
  await t('assert.typeOf', () => assert.typeOf(1, 'string'))
  await t('assert.fail', () => assert.fail('f'))
  await t('assert.closeTo', () => assert.closeTo(1, 2, 0.5))
  await t('assert.pass', () => assert.equal(1, 1))
