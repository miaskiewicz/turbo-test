const rows = []
const show = (v) => { try { return v === undefined ? 'undefined' : typeof v === 'function' ? 'fn' : typeof v === 'bigint' ? v + 'n' : JSON.stringify(v) } catch { return String(v) } }
const isAssertion = (v) => v instanceof chai.Assertion
const t = async (name, f) => { let r; try { const v = await f(); r = v === undefined ? 'passed' : isAssertion(v) ? 'assertion' : ['value', show(v)] } catch (e) { r = [e && e.name, e && e.message] } rows.push(JSON.stringify([name, r])) }
